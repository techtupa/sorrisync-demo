export const getPatientLeadsByTenant = (tenantId) => {
  return mockPatientLeads.filter((lead) => lead.tenant_id === tenantId);
};

export const getPatientLeadEventsByTenant = (tenantId, leadId = null) => {
  return mockPatientLeadEvents
    .filter((event) => event.tenant_id === tenantId)
    .filter((event) => !leadId || event.leadId === leadId)
    .sort((first, second) => new Date(second.occurredAt) - new Date(first.occurredAt));
};

export const getPatientLeadSummaryByTenant = (tenantId) => {
  const tenantLeads = getPatientLeadsByTenant(tenantId);

  return {
    total: tenantLeads.length,
    open: tenantLeads.filter((lead) => ![LEAD_STATUSES.CONVERTIDO, LEAD_STATUSES.PERDIDO].includes(lead.status)).length,
    converted: tenantLeads.filter((lead) => lead.status === LEAD_STATUSES.CONVERTIDO).length,
    lost: tenantLeads.filter((lead) => lead.status === LEAD_STATUSES.PERDIDO).length,
    scheduledFollowUps: tenantLeads.filter((lead) => lead.followUpAt && ![LEAD_STATUSES.CONVERTIDO, LEAD_STATUSES.PERDIDO].includes(lead.status)).length,
    urgent: tenantLeads.filter((lead) => lead.priority === LEAD_PRIORITIES.URGENTE).length,
  };
};
